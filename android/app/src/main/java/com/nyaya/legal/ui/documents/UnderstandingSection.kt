val EXPLANATION_LANGUAGES = listOf("en" to "English", "hi" to "हिन्दी", "hinglish" to "Hinglish")

/**
 * "Explained": a plain-language explanation of one document, generated by the backend and checked
 * there against the document (pages, quotes, values). Term meanings come from the curated glossary.
 */
@Composable
fun UnderstandingSection(
    understanding: Understanding?,
    loading: Boolean,
    error: String?,
    language: String,
    onLanguage: (String) -> Unit,
    onRegenerate: () -> Unit,
    onPage: (Int) -> Unit,
    onAsk: () -> Unit,
) {
    Column(verticalArrangement = Arrangement.spacedBy(10.dp)) {
        Row(verticalAlignment = Alignment.CenterVertically) {
            Text("Explained", style = MaterialTheme.typography.titleLarge, modifier = Modifier.weight(1f))
            IconButton(onClick = onRegenerate, enabled = !loading) { Icon(Icons.Default.Refresh, "Explain again") }
        }
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            EXPLANATION_LANGUAGES.forEach { (code, label) ->
                FilterChip(selected = language == code, onClick = { onLanguage(code) }, label = { Text(label) })
            }
        }
        if (loading) {
            LinearProgressIndicator(Modifier.fillMaxWidth())
            Text("Reading the document and explaining it in plain language…", style = MaterialTheme.typography.labelMedium)
        }
        error?.let { Text(it, color = MaterialTheme.colorScheme.error) }
        val u = understanding ?: return@Column

        Card(colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.secondaryContainer)) {
            Column(Modifier.padding(12.dp), verticalArrangement = Arrangement.spacedBy(4.dp)) {
                u.documentType?.let {
                    Text(
                        humanise(it) + if (!u.typeCheck.agrees) " (check: could also be ${humanise(u.typeCheck.ruleBased).lowercase()})" else "",
                        style = MaterialTheme.typography.labelLarge,
                    )
                }
                Text(u.oneLine, style = MaterialTheme.typography.bodyLarge)
            }
        }
        if (u.status != "complete") {
            Text(
                "The plain-language explanation isn't available right now (the AI service may be busy). " +
                    "Legal terms and checks below come from our own rules. Tap ↻ to try again.",
                style = MaterialTheme.typography.bodySmall,
            )
        }

        if (u.summary.isNotEmpty()) {
            SectionTitle("In simple words")
            u.summary.forEach { PointRow(it, onPage) }
        }
        if (u.clauses.isNotEmpty()) {
            SectionTitle("What the important parts mean")
            u.clauses.forEach { c ->
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(12.dp), verticalArrangement = Arrangement.spacedBy(4.dp)) {
                        Text(c.label, fontWeight = FontWeight.SemiBold)
                        Text(c.meaning, style = MaterialTheme.typography.bodyMedium)
                        c.quote?.let { Text("Original: “$it”", style = MaterialTheme.typography.bodySmall, fontStyle = FontStyle.Italic) }
                        PageChips(c.pages, c.verified, fromOcr = false, onPage)
                    }
                }
            }
        }
        if (u.terms.isNotEmpty()) {
            SectionTitle("Legal terms in this document")
            u.terms.forEach { TermCard(it, onPage) }
        }
        if (u.thingsToCheck.isNotEmpty()) {
            SectionTitle("Things to check")
            u.thingsToCheck.forEach { PointRow(it, onPage) }
        }
        Text(
            "This explains what the document says. It doesn't decide whether it is valid or who is right; " +
                "discuss that with an advocate.",
            style = MaterialTheme.typography.labelSmall,
        )
        Button(onClick = onAsk, modifier = Modifier.fillMaxWidth()) {
            Icon(Icons.AutoMirrored.Filled.Chat, null)
            Text("Ask about this document", Modifier.padding(start = 8.dp))
        }
    }
}

@Composable
private fun PointRow(point: ExplainedPoint, onPage: (Int) -> Unit) {
    Column {
        Text("• ${point.text}", style = MaterialTheme.typography.bodyMedium)
        PageChips(point.pages, point.verified || point.kind != null, point.fromOcr, onPage)
    }
}

/** "p.1 · p.2" links, plus whether the quote behind the statement was found on the page. */
@Composable
private fun PageChips(pages: List<Int>, verified: Boolean, fromOcr: Boolean, onPage: (Int) -> Unit) {
    if (pages.isEmpty()) return
    Row(horizontalArrangement = Arrangement.spacedBy(6.dp), verticalAlignment = Alignment.CenterVertically) {
        pages.forEach { p -> AssistChip(onClick = { onPage(p) }, label = { Text("p.$p") }) }
        Text(
            (if (verified) "" else "quote not confirmed") + (if (fromOcr) (if (verified) "" else " · ") + "read by OCR" else ""),
            style = MaterialTheme.typography.labelSmall,
            color = if (verified) MaterialTheme.colorScheme.onSurfaceVariant else MaterialTheme.colorScheme.error,
        )
    }
}

@Composable
private fun TermCard(term: TermExplained, onPage: (Int) -> Unit) {
    var open by remember { mutableStateOf(false) }
    Card(Modifier.fillMaxWidth().clickable { open = !open }) {
        Column(Modifier.padding(12.dp), verticalArrangement = Arrangement.spacedBy(4.dp)) {
            Text(term.term + (term.hindi?.let { " · $it" } ?: ""), fontWeight = FontWeight.SemiBold)
            Text(term.meaning, style = MaterialTheme.typography.bodyMedium)
            term.inThisDocument?.let { Text("Here: $it", style = MaterialTheme.typography.bodyMedium) }
            if (open) {
                Text("Why it matters: ${term.whyItMatters}", style = MaterialTheme.typography.bodySmall)
                term.law?.let { Text("Law: $it", style = MaterialTheme.typography.bodySmall) }
                term.excerpt?.let { Text("“…$it…”", style = MaterialTheme.typography.bodySmall, fontStyle = FontStyle.Italic) }
                term.page?.let { p -> AssistChip(onClick = { onPage(p) }, label = { Text("Appears on p.$p") }) }
            } else {
                Text("Tap for more", style = MaterialTheme.typography.labelSmall, color = MaterialTheme.colorScheme.primary)
            }
        }
    }
}
