class DocumentViewModel(private val caseId: String, private val docId: String) : ViewModel() {
    var document by mutableStateOf<DocumentDetail?>(null)
        private set
    var error by mutableStateOf<String?>(null)
        private set

    var understanding by mutableStateOf<Understanding?>(null)
        private set
    var language by mutableStateOf("en")
        private set
    var explaining by mutableStateOf(false)
        private set
    var explainError by mutableStateOf<String?>(null)
        private set

    private var explainJob: Job? = null

    init {
        viewModelScope.launch {
            runCatching { Api.service.document(caseId, docId) }
                .onSuccess {
                    document = it
                    if (it.status == "processed") explain()
                }
                .onFailure { error = Api.errorMessage(it) }
        }
    }

    /** Load the explanation in a language (generated by the backend on first request, then cached). */
    fun explain(lang: String = language, regenerate: Boolean = false) {
        language = lang
        explaining = true
        explainError = null
        explainJob?.cancel() // a slower answer for the previous language must not overwrite this one
        explainJob = viewModelScope.launch {
            val result = runCatching {
                if (regenerate) Api.service.regenerateUnderstanding(caseId, docId, lang)
                else Api.service.understanding(caseId, docId, lang)
            }
            // runCatching also catches the cancellation: a replaced request must change nothing.
            if (!isActive) return@launch
            result.onSuccess { understanding = it }.onFailure { explainError = Api.errorMessage(it) }
            explaining = false
        }
    }
}

/** One extracted item: its text and the page reference the extraction gave for it. */
private data class FactRow(val text: String, val source: SourceRef?)

// Sections of DocumentFacts (backend/app/llm/schemas.py) and how to describe each item.
private val SECTIONS: List<Pair<String, Pair<String, (JsonObject) -> String>>> = listOf(
    "parties" to ("Parties" to { o -> o.text("name").orEmpty() + (o.text("stated_role")?.let { " ($it)" } ?: "") }),
    "property_identifiers" to ("Property identifiers" to { o -> "${o.text("kind")}: ${o.text("value")}" }),
    "amounts" to ("Amounts" to { o -> "${o.text("description")}: ${o.text("value")}" }),
    "events" to ("Events" to { o -> listOfNotNull(o.text("date") ?: o.text("date_as_written"), o.text("description")).joinToString(": ") }),
    "clauses" to ("Clauses" to { o -> o.text("summary").orEmpty() }),
    "referenced_documents" to ("Documents it mentions" to { o -> o.text("description").orEmpty() }),
    "uncertainties" to ("Unclear or inconsistent" to { o -> o.text("description").orEmpty() }),
)

private fun JsonObject.sourceRef(doc: DocumentDetail): SourceRef? {
    val s = this["source"] as? JsonObject ?: return null
    return SourceRef(
        documentId = doc.id,
        filename = doc.filename,
        page = s["page"]?.jsonPrimitive?.intOrNull,
        excerpt = s.text("excerpt"),
        verified = s["verified"]?.jsonPrimitive?.booleanOrNull ?: false,
    )
}

private fun rows(doc: DocumentDetail, key: String, describe: (JsonObject) -> String): List<FactRow> =
    (doc.facts[key] as? JsonArray).orEmpty().mapNotNull { it as? JsonObject }.map { FactRow(describe(it), it.sourceRef(doc)) }

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun DocumentScreen(caseId: String, docId: String, page: Int?, onBack: () -> Unit, onAsk: (String) -> Unit) {
    val vm: DocumentViewModel = viewModel { DocumentViewModel(caseId, docId) }
    val listState = rememberLazyListState()
    val scope = rememberCoroutineScope()
    val doc = vm.document
    val sections = doc?.let { d -> SECTIONS.map { (key, spec) -> spec.first to rows(d, key, spec.second) }.filter { it.second.isNotEmpty() } }
    // Items before the page texts: notice, header, explanation, one per section. Used to jump to a cited page.
    val firstPageIndex = 3 + (sections?.size ?: 0) + if (sections.isNullOrEmpty()) 0 else 1
    val goToPage: (Int) -> Unit = { p ->
        if (doc != null && p in 1..doc.pages.size) scope.launch { listState.animateScrollToItem(firstPageIndex + p - 1) }
    }

    LaunchedEffect(doc, page) {
        if (doc != null && page != null && page in 1..doc.pages.size) listState.scrollToItem(firstPageIndex + page - 1)
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(doc?.filename ?: "Document") },
                navigationIcon = { IconButton(onClick = onBack) { Icon(Icons.AutoMirrored.Filled.ArrowBack, "Back") } },
            )
        },
    ) { padding ->
        when {
            vm.error != null -> ErrorText(vm.error!!, Modifier.padding(padding))
            doc == null || sections == null -> Column(Modifier.padding(padding)) { Loading("Loading…") }
            else -> LazyColumn(
                Modifier.fillMaxSize().padding(padding),
                state = listState,
                contentPadding = PaddingValues(16.dp),
                verticalArrangement = Arrangement.spacedBy(10.dp),
            ) {
                item { PreparationNotice() }
                item {
                    Text(
                        listOfNotNull(doc.documentType?.let(::humanise), doc.facts.text("document_date")?.let { "dated $it" })
                            .joinToString(", ").ifEmpty { "Extracted facts" },
                        style = MaterialTheme.typography.titleMedium,
                    )
                    doc.error?.let { Text(it, color = MaterialTheme.colorScheme.error) }
                    if (doc.status == "processing") {
                        Text("Facts are still being extracted. Go back and reopen in a moment; the page text is below.")
                    } else if (doc.facts.isEmpty() && doc.error == null) {
                        Text("No facts were extracted from this document.")
                    }
                }
                item {
                    if (doc.status == "processed") {
                        UnderstandingSection(
                            understanding = vm.understanding,
                            loading = vm.explaining,
                            error = vm.explainError,
                            language = vm.language,
                            onLanguage = { vm.explain(it) },
                            onRegenerate = { vm.explain(regenerate = true) },
                            onPage = goToPage,
                            onAsk = { onAsk(doc.id) },
                        )
                    }
                }
                if (sections.isNotEmpty()) item { SectionTitle("Details found in the document") }
                sections.forEach { (title, items) ->
                    item {
                        Card(Modifier.fillMaxWidth()) {
                            Column(Modifier.padding(12.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
                                Text(title, fontWeight = FontWeight.SemiBold)
                                items.forEach { row ->
                                    Text(row.text, style = MaterialTheme.typography.bodyMedium)
                                    row.source?.let { ref ->
                                        ref.excerpt?.let { Text("“$it”", style = MaterialTheme.typography.bodySmall) }
                                        // Tapping scrolls to the page text further down this screen.
                                        SourceLink(ref) { _, p ->
                                            if (p != null && p in 1..doc.pages.size) {
                                                scope.launch { listState.animateScrollToItem(firstPageIndex + p - 1) }
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
                itemsIndexed(doc.pages) { i, text ->
                    val info = doc.pageInfo.getOrNull(i)
                    val (label, warn) = pageLabel(info)
                    Column {
                        Text(
                            "Page ${i + 1}" + (label?.let { " · $it" } ?: ""),
                            style = MaterialTheme.typography.labelLarge,
                            fontWeight = FontWeight.SemiBold,
                            color = if (warn) MaterialTheme.colorScheme.error else MaterialTheme.colorScheme.onSurface,
                        )
                        Text(text.trim().ifEmpty { "(no text on this page)" }, style = MaterialTheme.typography.bodySmall)
                    }
                }
            }
        }
    }
}

/** How a page's text was obtained, and whether the user should double-check it. */
private fun pageLabel(info: JsonObject?): Pair<String?, Boolean> {
    val confidence = info?.get("confidence")?.jsonPrimitive?.doubleOrNull
    return when (info?.text("source")) {
        "ocr" -> {
            val low = confidence != null && confidence < 60
            ("read by OCR" + (confidence?.let { " (${it.toInt()}% confidence)" } ?: "") +
                if (low) ": low, check against the original" else "") to low
        }
        "ocr_pending" -> "reading the scan…" to false
        "ocr_unreadable" -> "scan too unclear to read" to true
        "ocr_failed" -> "OCR failed on this page" to true
        "ocr_unavailable" -> "scanned, OCR not available" to true
        "ocr_skipped" -> "not read (long scan, page limit)" to true
        else -> null to false
    }
}
